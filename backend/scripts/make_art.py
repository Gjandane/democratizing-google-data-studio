"""Vendored static art for designed pages (architecture.md#Designed pages, Art): three orthographic
globes and a flat world map from Natural Earth 110m Admin 0 countries, with stdlib math only.

uv run python scripts/make_art.py <ne_110m_admin_0_countries.geojson>

Natural Earth v5.1.2 is public domain; the GeoJSON stays out of git and nothing fetches it at runtime
or in tests. Every country is one path with `class="land <continent> c-<ISO_A3>"`, so page CSS colors
land, continents or single countries; a globe draws only the visible hemisphere inside an outline
circle. The same GeoJSON gives the same bytes.
"""
import argparse
import json
import math
from pathlib import Path
import re

OUT = Path(__file__).resolve().parents[1] / 'src/dss/render/art'
SOURCE = 'Natural Earth 1:110m Cultural Vectors, Admin 0 - Countries (ne_110m_admin_0_countries), v5.1.2'
LIMIT = 80 * 1024  # bytes per SVG
UNIT = 10  # path coordinates are rounded to 1/UNIT of a viewBox unit
SIZE, RADIUS = 500, 249  # globe viewBox side and outline radius
WIDTH, PAD = 1000, 2  # world map viewBox width and margin around the land
GLOBES = {  # name: centre (longitude, latitude)
    'globe-europe-africa': (15, 20),
    'globe-americas': (-75, 10),
    'globe-asia-pacific': (115, 10),
}
WORLD_SKIP = {'ATA'}  # the flat map leaves Antarctica out, like most dashboard world maps
LAND = 'fill="#CBD5E1" stroke="#FFFFFF" stroke-width=".6" stroke-linejoin="round" fill-rule="evenodd"'
OCEAN, OUTLINE = '#F1F5F9', '#94A3B8'
NOTICE = f'''The art in this folder (globe-europe-africa.svg, globe-americas.svg, globe-asia-pacific.svg,
world.svg) is generated by scripts/make_art.py from {SOURCE}:
https://github.com/nvkelso/natural-earth-vector (https://www.naturalearthdata.com/).

Licence: public domain. Natural Earth data is free to use in any project, with no permission
needed (https://www.naturalearthdata.com/about/terms-of-use/). Made with Natural Earth.
'''


def countries(path):
    """[(code, continent, polygons)] sorted by code; a polygon is a list of open (lon, lat) rings."""
    features, codes = [], set()
    for feature in json.loads(Path(path).read_text(encoding='utf-8'))['features']:
        p, geometry = feature['properties'], feature['geometry']
        # France and Norway carry ISO_A3 -99 in Natural Earth; ISO_A3_EH and ADM0_A3 still name them.
        code = next(c for c in (p['ISO_A3'], p['ISO_A3_EH'], p['ADM0_A3']) if re.fullmatch('[A-Z]{3}', c))
        if code in codes:
            raise SystemExit(f'Duplicate country code {code}')
        codes.add(code)
        continent = re.sub(r'[^a-z]+', '-', re.sub(r'\s*\(.*\)', '', p['CONTINENT']).lower()).strip('-')
        polygons = [geometry['coordinates']] if geometry['type'] == 'Polygon' else geometry['coordinates']
        polygons = [[ring[:-1] if ring[0] == ring[-1] else ring for ring in polygon] for polygon in polygons]
        features.append((code, continent, polygons))
    return sorted(features)


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def vector(lon, lat):
    lon, lat = math.radians(lon), math.radians(lat)
    return math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat)


class Globe:
    """Orthographic projection centred on (lon, lat): x east, y down, the horizon at RADIUS."""

    def __init__(self, lon, lat):
        self.centre = vector(lon, lat)
        lon, lat = math.radians(lon), math.radians(lat)
        self.east = (-math.sin(lon), math.cos(lon), 0.0)
        self.north = (-math.sin(lat) * math.cos(lon), -math.sin(lat) * math.sin(lon), math.cos(lat))

    def xy(self, v):
        return SIZE / 2 + RADIUS * dot(v, self.east), SIZE / 2 - RADIUS * dot(v, self.north)

    def angle(self, v):
        """Direction of v from the globe centre (y up); for a hidden point, where it meets the rim
        when the far side is pushed out onto the horizon."""
        return math.atan2(dot(v, self.north), dot(v, self.east))

    def rim(self, angle):
        return SIZE / 2 + RADIUS * math.cos(angle), SIZE / 2 - RADIUS * math.sin(angle)

    def clip(self, ring):
        """The ring's visible part as steps ('L', x, y) / ('A', x, y, sweep flag), starting with its
        first point; [] when hidden. A hidden run becomes rim arcs that follow its sweep around the
        horizon, which keeps the visible area and holes right whatever the ring's orientation."""
        points = [vector(*p) for p in ring]
        height = [dot(self.centre, v) for v in points]
        visible = [h > 0 for h in height]
        if all(visible):
            return [('L', *self.xy(v)) for v in points]
        if not any(visible):
            return []

        def crossing(i, j):  # where the edge i -> j meets the horizon plane, back on the sphere
            t = height[i] / (height[i] - height[j])
            v = [a + t * (b - a) for a, b in zip(points[i], points[j])]
            norm = math.sqrt(dot(v, v))
            return [c / norm for c in v]

        n = len(points)
        start = next(i for i in range(n) if visible[i] and not visible[i - 1])
        steps = [('L', *self.xy(crossing(start - 1, start)))]
        begin = sweep = previous = 0.0  # the hidden run's rim angle at its exit, its sweep so far, last angle
        for k in range(n):
            i, j = (start + k) % n, (start + k + 1) % n
            if visible[i]:
                steps.append(('L', *self.xy(points[i])))
                if not visible[j]:
                    exit_ = crossing(i, j)
                    steps.append(('L', *self.xy(exit_)))
                    begin = previous = self.angle(exit_)
                    sweep = 0.0
                continue
            sweep, previous = self._turn(sweep, previous, points[i])
            if visible[j]:
                entry = crossing(i, j)
                sweep, _ = self._turn(sweep, previous, entry)
                pieces = max(1, math.ceil(abs(sweep) / (math.pi / 2)))  # each arc <= 90 degrees
                for piece in range(1, pieces + 1):
                    x, y = self.xy(entry) if piece == pieces else self.rim(begin + sweep * piece / pieces)
                    steps.append(('A', x, y, int(sweep < 0)))  # SVG sweep flag 1 = clockwise on screen
        return steps

    def _turn(self, sweep, previous, v):
        angle = self.angle(v)
        turn = (angle - previous + math.pi) % (2 * math.pi) - math.pi
        if abs(turn) > 2.5:  # near the far pole the rim direction is unstable: move the centre
            raise SystemExit('A hidden ring passes too close to the far pole of a globe')
        return sweep + turn, angle


A1, A2, A3, A4 = 1.340264, -0.081106, 0.000893, 0.003796
M = math.sqrt(3) / 2


def equal_earth(lon, lat):
    """Equal Earth (Šavrič, Patterson, Jenny 2018), y down, in radius units."""
    t = math.asin(M * math.sin(math.radians(lat)))
    t2 = t * t
    t6 = t2 * t2 * t2
    x = math.radians(lon) * math.cos(t) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)))
    return x, -t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))


def number(tenths):
    """A rounded coordinate in its shortest SVG form: 12.3, .5, -.5, 7."""
    whole, part = divmod(abs(tenths), UNIT)
    text = (str(whole) if whole or not part else '') + (f'.{part}' if part else '')
    return ('-' if tenths < 0 else '') + text


def numbers(values):
    """SVG number list with the fewest separators: none before a minus sign, or before a leading
    dot after a number that already has one."""
    out, last = '', ''
    for value in map(number, values):
        joined = value[0] == '-' or (value[0] == '.' and '.' in last)
        out += ('' if joined or not out else ' ') + value
        last = value
    return out


def path_data(rings):
    """Absolute M and A, relative l, z per ring; a ring is steps from Globe.clip or ('L', x, y).
    Points are rounded to 1/UNIT and never repeat; a straight ring left with under 3 points is
    dropped (two points and a rim arc still enclose a sliver at the limb)."""
    parts = []
    for ring in rings:
        steps, seen = [], set()
        for kind, x, y, *flag in ring:
            point = (round(x * UNIT), round(y * UNIT))
            if steps and point == steps[-1][1]:
                continue
            steps.append((kind, point, flag))
            seen.add(point)
        if len(steps) > 1 and steps[-1][0] == 'L' and steps[-1][1] == steps[0][1]:
            steps.pop()  # z closes the ring; a closing rim arc stays
        if len(seen) < 2 or (len(seen) == 2 and all(kind == 'L' for kind, _, _ in steps)):
            continue
        text = 'M' + numbers(steps[0][1])
        here, relative = steps[0][1], False
        for kind, point, flag in steps[1:]:
            if kind == 'A':
                text += f'A{RADIUS} {RADIUS} 0 0 {flag[0]} ' + numbers(point)
                relative = False
            else:
                delta = numbers((point[0] - here[0], point[1] - here[1]))
                text += delta if relative and delta[0] == '-' else ((' ' if relative else 'l') + delta)
                relative = True
            here = point
        parts.append(text + 'z')
    return ''.join(parts)


def svg(comment, view_box, body):
    return (f'<!-- {comment}; generated by scripts/make_art.py -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}">\n{body}</svg>\n')


def country_paths(features, rings_of):
    lines = []
    for code, continent, polygons in features:
        d = path_data(ring for polygon in polygons for ring in rings_of(polygon))
        if d:
            lines.append(f'<path class="land {continent} c-{code}" d="{d}"/>\n')
    return f'<g class="countries" {LAND}>\n{"".join(lines)}</g>\n'


def globe(features, lon, lat):
    projection = Globe(lon, lat)
    disk = f'cx="{SIZE // 2}" cy="{SIZE // 2}" r="{RADIUS}"'
    body = (f'<circle class="ocean" {disk} fill="{OCEAN}"/>\n'
            + country_paths(features, lambda polygon: [projection.clip(ring) for ring in polygon])
            + f'<circle class="outline" {disk} fill="none" stroke="{OUTLINE}" stroke-width="1"/>\n')
    where = f'{abs(lon)}{"E" if lon >= 0 else "W"} {abs(lat)}{"N" if lat >= 0 else "S"}'
    return svg(f'{SOURCE} (public domain); orthographic globe centred on {where}', f'0 0 {SIZE} {SIZE}', body)


def world(features):
    features = [f for f in features if f[0] not in WORLD_SKIP]
    for code, _, polygons in features:
        for ring in (ring for polygon in polygons for ring in polygon):
            if any(abs(a[0] - b[0]) > 180 for a, b in zip(ring, ring[1:] + ring[:1])):
                raise SystemExit(f'{code} crosses the antimeridian: the flat map needs cut rings')
    projected = [(code, continent, [[[equal_earth(*p) for p in ring] for ring in polygon] for polygon in polygons])
                 for code, continent, polygons in features]
    xs = [x for *_, polygons in projected for polygon in polygons for ring in polygon for x, _ in ring]
    ys = [y for *_, polygons in projected for polygon in polygons for ring in polygon for _, y in ring]
    scale = (WIDTH - 2 * PAD) / (max(xs) - min(xs))
    height = math.ceil((max(ys) - min(ys)) * scale + 2 * PAD)
    place = lambda x, y: ('L', PAD + (x - min(xs)) * scale, PAD + (y - min(ys)) * scale)
    body = country_paths(projected, lambda polygon: [[place(*p) for p in ring] for ring in polygon])
    return svg(f'{SOURCE} (public domain); Equal Earth world map without Antarctica', f'0 0 {WIDTH} {height}', body)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('geojson', help='ne_110m_admin_0_countries.geojson (Natural Earth v5.1.2)')
    features = countries(parser.parse_args(argv).geojson)
    files = {f'{name}.svg': globe(features, *centre) for name, centre in GLOBES.items()}
    files['world.svg'] = world(features)
    files['NOTICE'] = NOTICE
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        data = text.encode('utf-8')
        if name.endswith('.svg') and len(data) > LIMIT:
            raise SystemExit(f'{name} is {len(data):,} bytes, over the {LIMIT:,}-byte limit')
        (OUT / name).write_bytes(data)  # LF line ends on every platform: byte-identical reruns
        print(f'{name}: {len(data):,} bytes')


if __name__ == '__main__':
    main()
